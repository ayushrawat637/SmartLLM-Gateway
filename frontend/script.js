
const API_BASE = "";

const elements = {
    apiStatus: document.getElementById("api-status-text"),
    cacheHits: document.getElementById("cache-hits"),
    cacheMisses: document.getElementById("cache-misses"),
    modelRequests: document.getElementById("model-requests"),
    fallbackEvents: document.getElementById("fallback-events"),
    lightweightRequests: document.getElementById("lightweight-requests"),
    advancedRequests: document.getElementById("advanced-requests"),
    cacheRate: document.getElementById("cache-rate"),
    cacheRing: document.getElementById("cache-ring"),
    cacheSummary: document.getElementById("cache-summary")
};

async function refreshMetrics() {
    try {
        const response = await fetch(`${API_BASE}/metrics`);

        if (!response.ok) {
            throw new Error(`Metrics request failed: ${response.status}`);
        }

        const metrics = await response.json();

        const hits = metrics.cache_hits ?? 0;
        const misses = metrics.cache_misses ?? 0;
        const lightweight = metrics.lightweight_model_requests ?? 0;
        const advanced = metrics.advanced_model_requests ?? 0;
        const fallbacks = metrics.fallback_events ?? 0;
        const totalRequests = lightweight + advanced;
        const totalCacheRequests = hits + misses;
        const hitRate = totalCacheRequests === 0
            ? 0
            : (hits / totalCacheRequests) * 100;

        elements.cacheHits.textContent = hits;
        elements.cacheMisses.textContent = misses;
        elements.modelRequests.textContent = totalRequests;
        elements.fallbackEvents.textContent = fallbacks;
        elements.lightweightRequests.textContent = lightweight;
        elements.advancedRequests.textContent = advanced;
        elements.cacheRate.textContent = `${hitRate.toFixed(1)}%`;

        elements.cacheRing.style.background =
            `conic-gradient(var(--green) ${hitRate}%, #e8efeb ${hitRate}%)`;

        elements.cacheSummary.textContent =
            `${hits} hits and ${misses} misses recorded`;

        elements.apiStatus.textContent = "Backend Online";
        elements.apiStatus.style.color = "var(--green-dark)";
    } catch (error) {
        elements.apiStatus.textContent = "Backend Offline";
        elements.apiStatus.style.color = "#dc2626";

        console.error("Could not refresh metrics:", error);
    }
}

refreshMetrics();
setInterval(refreshMetrics, 5000);


const questionForm = document.getElementById("question-form");
const questionInput = document.getElementById("question");
const askButton = document.getElementById("ask-button");
const answerPanel = document.getElementById("answer-panel");
const answerText = document.getElementById("answer-text");
const answerMeta = document.getElementById("answer-meta");

questionForm.addEventListener("submit", async (event) => {
    event.preventDefault();

    const question = questionInput.value.trim();

    if (!question) {
        questionInput.focus();
        return;
    }

    askButton.disabled = true;
    askButton.textContent = "Processing...";
    answerPanel.hidden = false;
    answerText.textContent = "Waiting for the gateway response...";
    answerMeta.textContent = "";

    try {
        const response = await fetch(`${API_BASE}/cache`, {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({ question })
        });

        const data = await response.json().catch(() => ({}));

        if (!response.ok) {
            throw new Error(
                data.detail || `Request failed with status ${response.status}`
            );
        }

        const answer = data.answer ?? data.response ?? data.result;

        
if (typeof answer === "string") {
    if (
        typeof marked !== "undefined" &&
        typeof DOMPurify !== "undefined"
    ) {
        const renderedMarkdown = marked.parse(answer);
        answerText.innerHTML = DOMPurify.sanitize(renderedMarkdown);
    } else {
        answerText.textContent = answer;
    }
} else {
    answerText.textContent = JSON.stringify(data, null, 2);
}


        const cacheStatus = data.cached === true
            ? "Cache HIT — answer reused from semantic cache"
            : "Cache MISS — answer generated by the LLM";

        answerMeta.textContent = cacheStatus;

        await refreshMetrics();
    } catch (error) {
        answerText.textContent = `Could not get an answer: ${error.message}`;
        answerMeta.textContent =
            "Check that the FastAPI server is running and inspect its terminal for errors.";
    } finally {
        askButton.disabled = false;
        askButton.textContent = "Send question";
    }
});
